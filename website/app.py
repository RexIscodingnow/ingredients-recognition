@app.route("/login", methods=["POST"])
def login():
    data = request.json
    email = data.get("email")
    password = data.get("password")

    if not email or not password:
        return redirect(url_for("home"))

    query_seq = access_db.query(tablename="Users", target={"email": email})
    if not query_seq:
        return jsonify(success=False, message='登入失敗：帳號或密碼錯誤')

    user = User(
        id=query_seq[0][0],
        username=query_seq[0][1],
        email=query_seq[0][2]
    )
    user.hashed_password = query_seq[0][3]
    if not user.verify_password(password):
        return jsonify(success=False, message='登入失敗：密碼錯誤')

    login_user(user, True, timedelta(hours=12))
    return jsonify(success=True, message=f'登入成功！歡迎 {user.username} 回來～', redirect_url=url_for("home"))


